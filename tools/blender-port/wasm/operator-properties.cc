/* As rna_access.cc gives the letter of an array item by the property's subtype. */
char RNA_property_array_item_char(PropertyRNA *prop, int index)
{
  const char *vectoritem = "XYZW", *quatitem = "WXYZ", *coloritem = "RGBA";
  if (index < 4) {
    switch (prop->subtype) {
      case PROP_QUATERNION:
        return quatitem[index];
      case PROP_TRANSLATION:
      case PROP_DIRECTION:
      case PROP_XYZ:
      case PROP_XYZ_LENGTH:
      case PROP_EULER:
      case PROP_VELOCITY:
      case PROP_ACCELERATION:
      case PROP_COORDS:
        return vectoritem[index];
      case PROP_COLOR:
      case PROP_COLOR_GAMMA:
        return coloritem[index];
      default:
        break;
    }
  }
  return 0;
}

/* The property of a name, reported as Blender's RNA reports a lookup of one the operator does not have. */
static PropertyRNA *find(PointerRNA *ptr, const char *name)
{
  if (!ptr->type) {
    return nullptr; /* PointerRNA_NULL: the properties of an operator button, which go nowhere (panel-layout.cc). */
  }
  PropertyRNA *prop = RNA_struct_find_property(ptr, name);
  if (!prop) {
    printf("%s: %s.%s not found.\n", __func__, ptr->type->identifier.c_str(), name);
  }
  return prop;
}

static long long read_int(const char *at, const DnaField &f)
{
  switch (f.size) {
    case 1: return f.is_signed ? *reinterpret_cast<const int8_t *>(at) : *reinterpret_cast<const uint8_t *>(at);
    case 2: return f.is_signed ? *reinterpret_cast<const int16_t *>(at) : *reinterpret_cast<const uint16_t *>(at);
    case 8: return *reinterpret_cast<const int64_t *>(at);
    default: return f.is_signed ? *reinterpret_cast<const int32_t *>(at) : *reinterpret_cast<const uint32_t *>(at);
  }
}

static void write_int(char *at, const DnaField &f, long long value)
{
  switch (f.size) {
    case 1: *reinterpret_cast<int8_t *>(at) = int8_t(value); break;
    case 2: *reinterpret_cast<int16_t *>(at) = int16_t(value); break;
    case 8: *reinterpret_cast<int64_t *>(at) = value; break;
    default: *reinterpret_cast<int32_t *>(at) = int32_t(value); break;
  }
}

/* A DNA property's element: where it is and, for a boolean stored as a bit, its mask. */
static std::pair<long long, int> dna_element(const PropertyRNA &prop, int i)
{
  const DnaField &f = *prop.dna;
  if (prop.type == PROP_BOOLEAN && f.bit) {
    return {f.bitset ? f.bit << i : f.bit, f.offset};
  }
  return {0, f.offset + i * f.size};
}

static std::vector<double> values(PointerRNA *ptr, const PropertyRNA *prop)
{
  if (!prop || !ptr->data) {
    return std::vector<double>(prop ? std::max(prop->length, 1) : 1, 0.0);
  }
  if (prop->dna) {
    const char *data = static_cast<const char *>(ptr->data);
    std::vector<double> out(std::max(prop->length, 1));
    for (size_t i = 0; i < out.size(); i++) {
      const auto [mask, offset] = dna_element(*prop, int(i));
      if (prop->dna->kind == 'f') {
        out[i] = *reinterpret_cast<const float *>(data + offset);
      }
      else if (prop->type == PROP_BOOLEAN) {
        const long long word = read_int(data + offset, *prop->dna);
        out[i] = ((mask ? (word & mask) != 0 : word != 0) != prop->dna->negative);
      }
      else {
        out[i] = double(read_int(data + offset, *prop->dna));
      }
    }
    return out;
  }
  const OperatorValues &set = *static_cast<OperatorValues *>(ptr->data);
  const auto it = set.numbers.find(prop);
  return it != set.numbers.end() ? it->second : prop->defaults;
}

static void set_values(PointerRNA *ptr, const PropertyRNA *prop, std::vector<double> numbers)
{
  if (!prop || !ptr->data) {
    return;
  }
  if (prop->dna) {
    char *data = static_cast<char *>(ptr->data);
    for (size_t i = 0; i < numbers.size(); i++) {
      const auto [mask, offset] = dna_element(*prop, int(i));
      if (prop->dna->kind == 'f') {
        *reinterpret_cast<float *>(data + offset) = float(numbers[i]);
      }
      else if (prop->type == PROP_BOOLEAN && mask) {
        const long long word = read_int(data + offset, *prop->dna);
        write_int(data + offset, *prop->dna, ((numbers[i] != 0.0) != prop->dna->negative) ? word | mask : word & ~mask);
      }
      else {
        write_int(data + offset, *prop->dna, (long long)(numbers[i]));
      }
    }
    return;
  }
  static_cast<OperatorValues *>(ptr->data)->numbers[prop] = std::move(numbers);
}

