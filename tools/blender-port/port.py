#!/usr/bin/env python3
"""Generates Bylonder's ports of Blender from tools/blender-port/manifest.json.

From the manifest's roots it follows every call through Clang into the file that defines it, and writes the closure
into `*.gen.js` modules, one per Blender module (convert.py has the conventions). Each public module, such as
bmesh-query.js, is hand-written shims plus `export * from './bmesh-query.gen.js'`: a shim exports the Blender name it
replaces, which wins over the generated one, and the generator skips it. Bylonder's divergences from Blender are
exactly its shims; a shim whose parameters differ from what the conventions make of Blender's signature is reported.

Writes tools/blender-port/status.json: per module, what is generated, shimmed (with any `port-override` reason and
signature difference),
excluded (with the manifest's reason, as a function that throws) or missing (no definition found, or a helper no
shim provides yet).

Units (manifest `units`) are self-contained parts built to WebAssembly from Blender's own sources instead (`--wasm`,
see wasm.py).

Usage: tools/blender-port/port.py SRC [--wasm | --units-only | --check FILE]   (SRC: Blender sources of the manifest's tag;
see convert.py). --check converts every function of one Blender file to stdout and counts its FIX marks by kind, in
seconds, to try a converter change; signatures from other files are known only in a full run.
"""
import collections
import glob
import json
import os
import re
import subprocess
import sys

import clang.cindex as ci

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import convert  # noqa: E402
import wasm  # noqa: E402
from rules import CONSTANTS  # noqa: E402

K = ci.CursorKind
HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(convert.REPO, 'src')
MARK = '// Generated by tools/blender-port/port.py'


def public_path(module):
    return os.path.join(SRC, module)


def gen_path(module):
    return public_path(module).removesuffix('.js') + '.gen.js'


def node(*args):
    result = subprocess.run(['node', os.path.join(HERE, 'js.mjs'), *args], capture_output=True, text=True)
    if result.returncode:
        sys.exit(f'js.mjs {args[0]} failed:\n{result.stderr}')
    return result.stdout


class Exports:
    """What each public module exports, with each function's parameters, read from its syntax tree."""

    def __init__(self):
        self.cache = {}

    def read(self, module):
        path = public_path(module)
        if path not in self.cache:
            self.cache[path] = json.loads(node('exports', path))[path] if os.path.exists(path) else {'exports': {}, 'needs': []}
        return self.cache[path]

    def of(self, module):
        return self.read(module)['exports'] if module else {}

    def needs(self, module):
        """Generated functions the module's shims call."""
        return self.read(module)['needs'] if module else []

    def forget(self, module):
        self.cache.pop(public_path(module), None)


class Driver:
    def __init__(self, root, manifest):
        self.root = root
        self.manifest = manifest
        self.exclude = manifest.get('exclude', {})
        self.exclude_modules = manifest.get('exclude_modules', {})
        self.units = manifest.get('units', {})
        self.registry = {}
        self.sources = {}
        self.exports = Exports()
        self.modules = {}  # module: {'functions': {name: item}, 'constants': {name: item}}
        self.status = {}
        self.home = {}  # name: the module that defines it

    def source(self, rel):
        if rel not in self.sources:
            print(f'parse {rel}', file=sys.stderr)
            self.sources[rel] = convert.Source(self.root, rel, self.registry, float32=self.manifest.get('float32', False))
        return self.sources[rel]

    def module_of(self, path):
        return convert.module_for(path if os.path.isabs(path) else os.path.join(self.root, path), self.root)

    def entry(self, module):
        return self.modules.setdefault(module, {'functions': {}, 'constants': {}})

    def note(self, module, kind, name, detail=None):
        status = self.status.setdefault(module or '(outside source/blender)', {'generated': [], 'shimmed': {}, 'excluded': {}, 'missing': {}})
        if kind == 'generated':
            status[kind].append(name)
        else:
            status[kind][name] = detail

    def excluded(self, module, name):
        return self.exclude.get(name) or next((r for prefix, r in self.exclude_modules.items() if module.startswith(prefix)), None)

    def definition_file(self, decl, source):
        """(file, parsed source) of the definition of the function `decl` declares: where the parsed source has it
        (its own file or an inline header), else the file named like the declaring header, then the rest of its
        directory, confirmed by parsing."""
        definition = decl.get_definition()
        if definition is not None and definition.location.file and not convert.is_prelude(definition):
            return convert.source_rel(definition.location.file.name, self.root), source.rel
        header = os.path.relpath(decl.location.file.name, self.root)
        directory = os.path.dirname(header)
        stem = os.path.splitext(os.path.basename(header))[0].removesuffix('_inline')
        candidates = [os.path.join(d, f'{s}.cc') for d in (directory, os.path.join(directory, 'intern'))
                      for s in (stem, stem.removeprefix('BLI_'), stem.removeprefix('BKE_'))]
        candidates += sorted(os.path.relpath(p, self.root) for p in glob.glob(os.path.join(self.root, directory, '**/*.cc'), recursive=True))
        for rel in dict.fromkeys(candidates):
            path = os.path.join(self.root, rel)
            if os.path.exists(path) and decl.spelling in open(path, errors='replace').read() and self.source(rel).find(decl.spelling) is not None:
                return rel, rel
        return None

    def run(self):
        # (file defining the function, function, the parsed file that holds its definition)
        queue = [(root['source'], name, root['source']) for root in self.manifest['roots'] for name in root['functions']]
        done = set()
        while queue:
            rel, name, provider = queue.pop(0)
            if (rel, name) in done:
                continue
            done.add((rel, name))
            module = self.module_of(rel)
            if module is None:
                self.note(None, 'excluded', name, rel)
                continue
            self.home.setdefault(name, module)
            if name in self.exports.of(module):
                self.note(module, 'shimmed', name, self.check_shim(provider, rel, module, name))
                # What the shim calls of Blender's, looked for in the same file first.
                queue += [(rel, need, provider) for need in self.exports.needs(module)]
                continue
            reason = self.excluded(module, name)
            if reason:
                self.stub(module, name, reason)
                continue
            source = self.source(provider)
            f = source.definition(name, rel)
            if f is None:
                self.note(module, 'missing', name, f'no definition in {rel}')
                continue
            js, deps = source.emit(f)
            self.entry(module)['functions'][name] = {'key': (rel, f.extent.start.offset), 'js': js, 'deps': deps,
                                                     'exported': f.linkage != ci.LinkageKind.INTERNAL or rel.endswith(('.hh', '.h')),
                                                     'source': provider, 'file': rel}
            queue += self.follow(source, rel, module, deps)
        # Again, now that every signature is known: out parameters and `bm` across files.
        for module, entry in self.modules.items():
            for name, item in entry['functions'].items():
                if 'source' in item:
                    source = self.sources[item['source']]
                    item['js'], item['deps'] = source.emit(source.definition(name, item['file']))
                    self.follow(source, item['source'], module, item['deps'])
                    self.note(module, 'generated', name)

    def follow(self, source, rel, module, deps):
        """The functions deps reach, to port next. Constants are placed and helpers checked on the way."""
        queue = []
        for kind, name, ref in deps:
            if kind == 'function':
                home = self.module_of(ref.location.file.name)
                reason = home and not source.in_main(ref) and self.excluded(home, name)
                if reason:
                    self.stub(home, name, reason)
                    continue
                where = (rel, source.rel) if source.in_main(ref) else self.definition_file(ref, source)
                if where:
                    queue.append((where[0], name, where[1]))
                else:
                    self.home.setdefault(name, home)
                    if name not in self.exports.of(home):
                        self.note(home, 'missing', name, 'no definition found')
            elif kind == 'constant':
                self.constant(source, module, name, ref)
            elif kind == 'helper':
                if ref is None:
                    self.note(None, 'missing', name, 'prelude macro without a home in rules.PRELUDE_HOMES')
                    continue
                self.home.setdefault(name, ref)
                if name in self.exclude:
                    self.stub(ref, name, self.exclude[name])
                elif name not in self.exports.of(ref):
                    self.note(ref, 'missing', name, 'helper without a shim')
        return queue

    def stub(self, module, name, reason):
        """An excluded name: a function that says why it is not ported, so callers import it and the gap shows."""
        self.note(module, 'excluded', name, reason)
        self.home.setdefault(name, module)
        if name not in self.exports.of(module):
            message = json.dumps(f'{name} is not ported: {reason}')
            self.entry(module)['functions'][name] = {'key': ('~', name), 'js': f'function {name}() {{\n  throw new Error({message});\n}}',
                                                     'deps': set(), 'exported': True}

    def check_shim(self, provider, rel, module, name):
        """The shim's port-override reason, and both parameter lists when they differ from what the conventions
        make of Blender's signature; None when neither applies."""
        shim = self.exports.of(module)[name]
        detail = {'override': shim['override']} if shim['override'] else {}
        source = self.source(provider)
        f = source.definition(name, rel)
        if f is not None and shim['params'] is not None:
            fp = convert.FunctionPort(source, f)
            fp.emit()
            want = [p['name'] for p in fp.sig['params'] if p['out'] != 'out']
            if fp.sig.get('needs_bm'):
                want.insert(0, 'bm')
            if len(want) != len(shim['params']):
                detail['signature'] = f'Blender ({", ".join(want)}), shim ({", ".join(shim["params"])})'
        return detail or None

    def constant(self, source, module, name, ref):
        """An enum, file-scope variable or macro constant, written in the module of the file that defines it."""
        if name in CONSTANTS:
            return
        if isinstance(ref, tuple):  # A macro: (definition, JS value).
            decl, value = ref
            names, js = [name], f'const {name} = {value};'
        elif ref.kind == K.ENUM_CONSTANT_DECL:
            decl = ref.semantic_parent
            values = [e for e in decl.get_children() if e.kind == K.ENUM_CONSTANT_DECL]
            if decl.is_scoped_enum():
                # An enum class keeps its scope: PolyIndexFlag.IndexCacheDirty.
                names = [decl.spelling]
                js = f'const {decl.spelling} = Object.freeze({{ {", ".join(f"{e.spelling}: {e.enum_value}" for e in values)} }});'
            else:
                names, js = [e.spelling for e in values], f'const {", ".join(f"{e.spelling} = {e.enum_value}" for e in values)};'
        else:
            decl = ref
            init = convert.clangx.var_init(ref)
            fp = convert.FunctionPort(source, None, {'params': [], 'ret': ref.type})
            names, js = [name], f'const {name} = {fp.expr(init, ref.type) if init is not None else convert.zero_of(ref.type)};'
        if decl is None or not decl.location.file:
            return
        local = source.in_main(decl)
        target = module if local else self.module_of(decl.location.file.name)
        if not target:
            return
        for n in names:
            self.home[n] = target
        if not local and all(n in self.exports.of(target) for n in names):
            return
        key = (source.rel if local else os.path.relpath(decl.location.file.name, self.root), decl.extent.start.offset)
        self.entry(target)['constants'][names[0]] = {'key': key, 'js': js, 'exported': not local, 'names': names}

    def write(self):
        tag = self.manifest['blender']
        for module, entry in sorted(self.modules.items()):
            defined = set(entry['functions']) | {n for c in entry['constants'].values() for n in c['names']}
            constants = [('export ' if c['exported'] else '') + c['js'] for c in sorted(entry['constants'].values(), key=lambda c: c['key'])]
            functions = [('export ' if f['exported'] else '') + f['js'] for f in sorted(entry['functions'].values(), key=lambda f: f['key'])]
            imports = {}
            for f in entry['functions'].values():
                for kind, name, ref in f['deps']:
                    home = ref if kind == 'helper' else self.home.get(name)
                    if home and name not in defined:
                        imports.setdefault(home, set()).add(name)
            lines = []
            for home, names in sorted(imports.items()):
                path = os.path.relpath(public_path(home), os.path.dirname(gen_path(module)))
                lines.append(f"import {{ {', '.join(sorted(names))} }} from '{path if path.startswith('.') else './' + path}';")
            header = (f'{MARK} from Blender {tag}. Do not edit: fix the converter, or replace a function by\n'
                      f'// exporting the same name from {os.path.basename(public_path(module))}.\n')
            os.makedirs(os.path.dirname(gen_path(module)), exist_ok=True)
            open(gen_path(module), 'w').write(header + '\n'.join(lines) + '\n\n' + '\n'.join(constants) + '\n\n' + '\n\n'.join(functions) + '\n')
            self.link(module, gen_path(module))
        self.prune()
        node('format', *[gen_path(m) for m in sorted(self.modules)])
        status = {m: self.status[m] for m in sorted(self.status)}
        open(os.path.join(HERE, 'status.json'), 'w').write(json.dumps(status, indent=2) + '\n')

    def link(self, module, generated):
        """The public module re-exports the generated one; a new one starts as just that."""
        path = public_path(module)
        star = f"export * from './{os.path.basename(generated)}';"
        if not os.path.exists(path):
            open(path, 'w').write(f'// Shims for {module}: export a Blender name here to replace its generated port.\n{star}\n')
        elif star not in open(path).read().split('\n'):
            open(path, 'a').write(f'\n{star}\n')
        self.exports.forget(module)

    def prune(self):
        """Generated modules the manifest no longer reaches go, with their re-export."""
        for path in glob.glob(os.path.join(SRC, '**/*.gen.js'), recursive=True):
            module = os.path.relpath(path, SRC).removesuffix('.gen.js').removesuffix('.unit') + '.js'
            unit_file = path.endswith('.unit.gen.js')
            if (module in self.units if unit_file else module in self.modules) or not open(path).read().startswith(MARK):
                continue
            if unit_file and os.path.exists(path.replace('.unit.gen.js', '.wasm')):
                os.remove(path.replace('.unit.gen.js', '.wasm'))
            os.remove(path)
            public = public_path(module)
            if os.path.exists(public):
                star = f"export * from './{os.path.basename(path)}';"
                kept = [line for line in open(public).read().split('\n') if line != star]
                if all(not line.strip() or line.startswith('//') for line in kept):
                    os.remove(public)
                else:
                    open(public, 'w').write('\n'.join(kept))


def check(driver, rel):
    source = driver.source(rel)
    js = '\n\n'.join(source.emit(f)[0] for f in source.functions)
    print(js)
    fixes = collections.Counter(m.group(1) for m in re.finditer(r'/\*FIX ([^*:]*)', js))
    print(f'{len(source.functions)} functions, {sum(fixes.values())} FIX marks: {dict(fixes.most_common())}', file=sys.stderr)


def main():
    root = sys.argv[1]
    manifest = json.load(open(os.path.join(HERE, 'manifest.json')))
    driver = Driver(root, manifest)
    if '--check' in sys.argv:
        return check(driver, sys.argv[sys.argv.index('--check') + 1])
    if '--units-only' not in sys.argv:
        driver.run()
        driver.write()
    if '--wasm' in sys.argv or '--units-only' in sys.argv:
        units = wasm.build_units(driver)
        node('format', *units)
        for module, path in zip(driver.units, units):
            driver.link(module, path)
        if '--units-only' in sys.argv:
            return
    generated = sum(len(s['generated']) for s in driver.status.values())
    fixes = sum(f['js'].count('/*FIX') for e in driver.modules.values() for f in e['functions'].values())
    print(f'{generated} functions generated, {fixes} FIX marks', file=sys.stderr)
    for module, status in driver.status.items():
        if status['missing']:
            print(f'missing in {module}: {", ".join(status["missing"])}', file=sys.stderr)
        for name, detail in status['shimmed'].items():
            if detail:
                print(f'shim {module} {name}: {detail}', file=sys.stderr)


if __name__ == '__main__':
    main()
