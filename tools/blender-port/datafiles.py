"""Blender's datafiles, from a Blender install at the manifest's tag: the asset libraries of Blender's Essentials the
module reads at run time (node groups such as Hair Dynamics, the curve and mesh sculpt brushes) and their catalogs, which the
module's realm puts in its file system at Blender's system directory (src/bmesh/bmesh-wasm.js, ghost-paths.cc); and the
studio light Material Preview lights the view with (STUDIOLIGHT_WORLD_DEFAULT, studiolight.cc), which the view loads.
Writes src/bmesh/datafiles/ and src/bmesh/datafiles.js.

usage: python3 tools/blender-port/datafiles.py [BLENDER_INSTALL]   (default .blender-reference/blender-<tag>-linux-x64)
"""
import json
import os
import shutil
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
FILES = ['assets/blender_assets.cats.txt', 'assets/nodes/geometry_nodes_essentials.blend',
         'assets/nodes/geometry_nodes_dynamics_assets.blend', 'assets/nodes/procedural_hair_node_assets.blend',
         'assets/brushes/essentials_brushes-curve_sculpt.blend', 'assets/brushes/essentials_brushes-mesh_sculpt.blend']
STUDIO_LIGHT = 'studiolights/world/forest.exr'
# Written again by Blender with ZIP compression: Blender ships it as DWAB, which Babylon's EXR loader does not read.
REENCODE = ("import bpy, sys; image = bpy.data.images.load(sys.argv[-2]); s = bpy.context.scene.render.image_settings; "
            "s.file_format, s.exr_codec, s.color_depth = 'OPEN_EXR', 'ZIP', '16'; image.save_render(sys.argv[-1])")
# Their licenses, kept beside them; Blender does not read them.
LICENSES = ['assets/LICENSE', 'studiolights/world/license.txt']


def main():
    tag = json.load(open(os.path.join(REPO, 'tools/blender-port/manifest.json')))['blender'].lstrip('v')
    install = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, '.blender-reference', f'blender-{tag}-linux-x64')
    source = os.path.join(install, '.'.join(tag.split('.')[:2]), 'datafiles')
    out = os.path.join(REPO, 'src', 'bmesh', 'datafiles')
    shutil.rmtree(out, ignore_errors=True)
    for name in FILES + [STUDIO_LIGHT] + LICENSES:
        os.makedirs(os.path.dirname(os.path.join(out, name)), exist_ok=True)
        shutil.copyfile(os.path.join(source, name), os.path.join(out, name))
    subprocess.run([os.path.join(install, 'blender'), '-b', '--factory-startup', '--python-expr', REENCODE, '--',
                    os.path.join(source, STUDIO_LIGHT), os.path.join(out, STUDIO_LIGHT)], check=True, capture_output=True)
    # Literal URLs, which the bundler resolves as it resolves the module's own.
    with open(os.path.join(REPO, 'src', 'bmesh', 'datafiles.js'), 'w') as f:
        f.write('// Generated by tools/blender-port/datafiles.py: Blender\'s datafiles the module reads, by path under its datafiles.\n')
        f.write('export const DATAFILES = [\n' + ''.join(f"  ['{name}', new URL('./datafiles/{name}', import.meta.url)],\n" for name in FILES) + '];\n')
        f.write("// Material Preview's studio light.\n")
        f.write(f"export const STUDIO_LIGHT = new URL('./datafiles/{STUDIO_LIGHT}', import.meta.url);\n")
    print(f'wrote {len(FILES)} datafiles of Blender {tag} to src/bmesh/datafiles')


if __name__ == '__main__':
    main()
