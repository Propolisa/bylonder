// Bundles the page's loaders of Blender's kernel modules into standalone modules: the modifier kernels' worker
// (src/io_scene_babylon/polyfill/worker.js) into modifiers-worker.bundle.js, which Live Modifiers exports ship next to
// modifiers.wasm, and the Geometry Nodes kernels' loader (polyfill/geometry-nodes.js) into
// geometry-nodes-kernels.bundle.js, shipped next to geometry-nodes.wasm, and the volume passes (polyfill/volumes.js) into
// volumes.bundle.js, Babylon left to the page's import map.
// usage: node scripts/modifiers-polyfill.mjs [--check]
import { fileURLToPath, pathToFileURL } from 'node:url';
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild-wasm';

const dir = new URL('../src/io_scene_babylon/polyfill/', import.meta.url);
export const BUNDLES = { 'modifiers-worker.bundle.js': 'worker.js', 'geometry-nodes-kernels.bundle.js': 'geometry-nodes.js', 'volumes.bundle.js': 'volumes.js' };

export async function bundle(name) {
  const entry = BUNDLES[name];
  const result = await build({ entryPoints: [fileURLToPath(new URL(entry, dir))], bundle: true, format: 'esm', target: 'es2022', write: false, legalComments: 'none',
    external: ['@babylonjs/core'] });
  return `// Generated by scripts/modifiers-polyfill.mjs from src/io_scene_babylon/polyfill/${entry}. Do not edit.\n` + result.outputFiles[0].text;
}

/** Whether a bundle is current. @param {string} name */
export const current = async (name) => readFileSync(new URL(name, dir), 'utf8') === await bundle(name);

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
  for (const name of Object.keys(BUNDLES)) {
    if (!process.argv.includes('--check')) writeFileSync(new URL(name, dir), await bundle(name));
    else if (!await current(name)) throw Error(`${name} is out of date: run node scripts/modifiers-polyfill.mjs`);
  }
}
