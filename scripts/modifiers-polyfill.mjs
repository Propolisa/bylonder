// Bundles the modifier kernels polyfill's worker (src/io_scene_babylon/polyfill/worker.js) into one standalone module,
// modifiers-worker.bundle.js, which Live modifiers exports ship next to modifiers.js and modifiers.wasm.
// usage: node scripts/modifiers-polyfill.mjs [--check]
import { readFileSync, writeFileSync } from 'node:fs';
import { build } from 'esbuild-wasm';

const dir = new URL('../src/io_scene_babylon/polyfill/', import.meta.url);
const out = new URL('modifiers-worker.bundle.js', dir);

export async function bundleWorker() {
  const result = await build({ entryPoints: [new URL('worker.js', dir).pathname], bundle: true, format: 'esm', target: 'es2022', write: false, legalComments: 'none' });
  return '// Generated by scripts/modifiers-polyfill.mjs from src/io_scene_babylon/polyfill/worker.js. Do not edit.\n' + result.outputFiles[0].text;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const text = await bundleWorker();
  if (process.argv.includes('--check')) {
    if (readFileSync(out, 'utf8') !== text) throw Error('modifiers-worker.bundle.js is out of date: run node scripts/modifiers-polyfill.mjs');
  } else writeFileSync(out, text);
}
