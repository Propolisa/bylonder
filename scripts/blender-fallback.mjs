// Bundles an exported page's Blender fallback (src/io_scene_babylon/blender-fallback.js) into one module that imports
// only @babylonjs/core and finds Blender's module, bmesh.wasm, beside it: a package's bylonder-blender/blender.js.
// Blender's datafiles (asset libraries, color management) stay out; the fallback evaluates without them.
// usage: node scripts/blender-fallback.mjs <out.js>
import { fileURLToPath } from 'node:url';
import { writeFileSync } from 'node:fs';
import { build } from 'esbuild-wasm';

const src = new URL('../src/', import.meta.url);
const page = {
  name: 'page',
  setup(bundle) {
    // Babylon is the page's: its deep imports are the package's named exports.
    bundle.onResolve({ filter: /^@babylonjs\/core(\/.*)?$/ }, () => ({ path: '@babylonjs/core', external: true }));
    bundle.onResolve({ filter: /\/datafiles\.js$/ }, () => ({ path: 'datafiles', namespace: 'page' }));
    bundle.onLoad({ filter: /^datafiles$/, namespace: 'page' }, () => ({ contents: 'export const DATAFILES = [], COLOR_MANAGEMENT = [], STUDIO_LIGHT = null;' }));
  },
};

export async function bundleFallback() {
  const result = await build({ entryPoints: [fileURLToPath(new URL('io_scene_babylon/blender-fallback.js', src))], bundle: true, format: 'esm', target: 'es2022',
    write: false, legalComments: 'none', plugins: [page], logLevel: 'error' });
  return '// Generated by scripts/blender-fallback.mjs from src/io_scene_babylon/blender-fallback.js: GPL-2.0-or-later, as Blender is.\n' + result.outputFiles[0].text;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) writeFileSync(process.argv[2], await bundleFallback());
