import assert from 'node:assert/strict';
import { NullEngine, Scene, MeshBuilder, StandardMaterial, Color3 } from '@babylonjs/core';
import { createAnimationModel } from '../src/blenkernel/animation/model.js';
import { address } from '../src/blenkernel/animation/model.js';
import { createMaterialLibrary, materialId } from '../src/blenkernel/material/library.js';
const engine = new NullEngine(), scene = new Scene(engine);
const a = MeshBuilder.CreateBox('A', {}, scene), b = MeshBuilder.CreateBox('B', {}, scene);
a.metadata = { wbId: 'a' }; b.metadata = { wbId: 'b' };
const paint = new StandardMaterial('Paint', scene); paint.diffuseColor = new Color3(1, 0, 0); a.material = paint;
const objects = [a, b]; objects.scene = scene;
const world = { scene, objects, animation: createAnimationModel() };
let commits = 0;
const lib = createMaterialLibrary(world, { commit: () => commits++ });
const saved = lib.capture();
lib.assign(b, 0, paint);
assert.equal(lib.users(paint), 2, 'linked material counts both users');
lib.makeSingleUser(b);
const copy = lib.activeMaterial(b);
assert.notEqual(copy, paint); assert.equal(copy.name, 'Paint.001'); assert.equal(lib.users(paint), 1);
lib.addSlot(a); assert.equal(lib.slots(a).length, 2); assert.equal(a.material.getClassName(), 'MultiMaterial');
const pbr = lib.convert(paint, 'pbr');
assert.equal(pbr.getClassName(), 'PBRMaterial'); assert.equal(materialId(pbr), 'Paint'); assert.ok(pbr.albedoColor.equals(new Color3(1, 0, 0)));
world.animation.channels.get(address('material:Paint', 'roughness')).set(0.2);
assert.equal(pbr.roughness, 0.2, 'converted material registers animatable channels');
const edited = JSON.parse(JSON.stringify(lib.capture()));
lib.apply(saved);
assert.equal(a.material, paint, 'apply restores the original code material and slots');
assert.equal(b.material, null);
lib.apply(edited);
assert.equal(lib.activeMaterial(b).name, 'Paint.001');
assert.equal(lib.slots(a)[0].getClassName(), 'PBRMaterial');
const shared = lib.slots(a)[0];
lib.assign(b, 0, null);
const orphan = lib.create('standard', 'Orphan');
assert.ok(lib.capture().created.some(c => c.id === materialId(orphan)), 'undo keeps zero-user materials');
assert.ok(!lib.capture({ save: true }).created.some(c => c.id === materialId(orphan)), 'saving drops zero-user materials');
lib.toggleFakeUser(orphan);
assert.ok(lib.capture({ save: true }).created.some(c => c.id === materialId(orphan)), 'fake user keeps it on save');
world.animation.channels.get(address('material:Paint', 'alpha')).set(0.4);
assert.equal(shared.alpha, 0.4, 'shared channels follow the converted material, not the disposed one');
assert.ok(commits > 0);
console.log('Materials: linking, single-user copies, slots, conversion, channels and capture/apply round-trip passed');
