import assert from 'node:assert/strict';
import { NullEngine, Scene, MeshBuilder } from '@babylonjs/core';
import { createAnimationModel } from '../src/animation/model.js';
import { createCollections, MASTER } from '../src/scene/collections.js';
import { createRenderSettings } from '../src/scene/render.js';
import { createSceneTime } from '../src/scene/time.js';

const engine = new NullEngine(), scene = new Scene(engine);
const [a, b, c] = ['A', 'B', 'C'].map(n => { const m = MeshBuilder.CreateBox(n, {}, scene); m.metadata = { wbId: n }; return m; });
c.isVisible = false;
const objects = [a, b, c]; objects.scene = scene;
const world = { scene, objects, animation: createAnimationModel() };
let commits = 0;
const cols = createCollections(world, { commit: () => commits++ });
assert.equal(cols.capture(), undefined, 'untouched collections save nothing');
assert.deepEqual(cols.objects(MASTER), ['A', 'B', 'C'], 'objects linked nowhere are Scene Collection members');
const props = cols.create({ objects: ['A', 'C'], move: true });
assert.equal(props.name, 'Collection');
assert.deepEqual(cols.objects(MASTER), ['B']);
cols.setLayer(props.id, { exclude: true });
assert.equal(a.isVisible, false, 'excluding a collection hides its objects');
assert.equal(cols.status(a).inLayer, false);
cols.link(['A'], MASTER);
assert.equal(a.isVisible, true, 'an object visible through any path stays visible');
cols.unlink(['A'], MASTER);
cols.setLayer(props.id, { exclude: false });
assert.equal(a.isVisible, true); assert.equal(c.isVisible, false, 'authored isVisible is never overridden');
cols.set(props.id, { hideSelect: true });
assert.equal(cols.selectable(a), false); assert.equal(cols.selectable(b), true);
const child = cols.create({ parent: props.id, objects: ['B'], move: true });
cols.set(props.id, { hideViewport: true });
assert.equal(b.isVisible, false, 'disabling a parent collection hides nested collections');
cols.set(props.id, { hideViewport: false });
const layerTwo = cols.createViewLayer();
cols.setLayer(child.id, { hideViewport: true });
assert.equal(b.isVisible, false);
cols.setViewLayer('ViewLayer');
assert.equal(b.isVisible, true, 'layer collection flags are per view layer');
cols.setViewLayer(layerTwo.id);
cols.remove(props.id);
assert.deepEqual(cols.state.scene.children, [child.id], 'deleting a collection moves children to the parent');
assert.ok(cols.objects(MASTER).includes('A'), 'and its objects');
const saved = cols.capture();
cols.apply(undefined);
assert.equal(b.isVisible, true); assert.equal(cols.all().length, 0);
cols.apply(saved);
assert.equal(b.isVisible, false);
const d = MeshBuilder.CreateBox('D', {}, scene); d.metadata = { wbId: 'D' }; objects.push(d);
cols.setActive(child.id); cols.adopt();
assert.deepEqual(cols.memberships('D'), [child.id], 'new objects go to the active collection');

const render = createRenderSettings(world);
assert.equal(render.capture(), undefined);
render.set('viewSettings.viewTransform', 'KHR_PBR_NEUTRAL');
render.set('viewSettings.exposure', 1);
assert.equal(scene.imageProcessingConfiguration.toneMappingEnabled, true);
assert.equal(scene.imageProcessingConfiguration.exposure, 2, 'exposure is in stops');
assert.deepEqual(render.capture(), { viewSettings: { viewTransform: 'KHR_PBR_NEUTRAL', exposure: 1 } });
render.apply(undefined);
assert.equal(scene.imageProcessingConfiguration.toneMappingEnabled, false);

const time = createSceneTime();
time.configure({ usePreviewRange: true, framePreviewStart: 10, framePreviewEnd: 20, frameStep: 2 });
time.seek(19); time.play(); time.tick(0); time.tick(1000 / 24 * 3);
assert.equal(time.frame, 12, 'playback loops inside the preview range, stepping by frame step');
assert.throws(() => time.configure({ frameStart: 300 }), /frame range/);
console.log('Collections, view layers, render settings and scene time passed');
