import assert from 'node:assert/strict';
import { createAnimationModel, address } from '../src/blenkernel/animation/model.js';
import { createDocument, channelSlice } from '../src/blenkernel/document.js';
const animation = createAnimationModel();
const target = { roughness: 0.5, owned: 1 };
animation.register({ id: 'material:a', path: 'roughness', label: 'Roughness', get: () => target.roughness, set: v => { target.roughness = v; } });
animation.register({ id: 'store:s', path: 'owned', label: 'Owned', get: () => target.owned, set: v => { target.owned = v; } });
let state = { count: 0 };
const doc = createDocument();
doc.register('counter', { capture: () => ({ ...state }), apply: s => { state = { count: 0, ...s }; } });
doc.register('channels', channelSlice(animation, channel => channel.id.startsWith('store:')));
assert.throws(() => doc.register('counter', {}), /Duplicate/);
state.count = 3;
animation.channels.get(address('material:a', 'roughness')).set(0.1);
target.owned = 9;
const saved = JSON.parse(JSON.stringify(doc.capture()));
assert.deepEqual(saved, { counter: { count: 3 }, channels: { [address('material:a', 'roughness')]: 0.1 } }, 'channels persist as a diff and skip owned refs');
doc.apply(undefined);
assert.equal(state.count, 0); assert.equal(target.roughness, 0.5, 'missing state restores code defaults');
assert.equal(target.owned, 9, 'owned channels are left to their slice');
doc.apply(saved);
assert.equal(state.count, 3); assert.equal(target.roughness, 0.1);
console.log('Document: slice registry, channel diffs, defaults and ownership passed');
