import assert from 'node:assert/strict';
import { NullEngine, Scene, MeshBuilder, NodeMaterial, InputBlock, Color3, ArcRotateCamera, Vector3 } from '@babylonjs/core';
import { createAnimationModel, address } from '../src/blenkernel/animation/model.js';
import { bindGraph } from '../src/nodes/bindings.js';
import { geometryNodesDefinition } from '../src/nodes/geometry-nodes.js';
import { createModifierSystem, registerModifier } from '../src/modifiers/stack.js';
import { createHistory } from '../src/editors/undo/storage.js';
import { createLogic } from '../src/nodes/logic.js';
const engine = new NullEngine(), scene = new Scene(engine);
new ArcRotateCamera('c', 0, 1, 5, Vector3.Zero(), scene);
const animation = createAnimationModel();
const material = new NodeMaterial('Paint', scene);
material.setToDefault();
material.build();
const tint = material.getInputBlocks().find(b => b.isUniform && !b.isSystemValue && b.value instanceof Object && 'r' in b.value);
assert.ok(tint, 'default node material exposes a uniform color input');
const fields = bindGraph(animation, { id: 'material:Paint:graph', title: 'Paint', graph: material, kind: 'material' });
assert.ok(fields.some(f => f.color), 'color inputs are reflected as color fields');
animation.channels.get(address('material:Paint:graph', tint.name + '.g')).set(0.25);
assert.equal(tint.value.g, 0.25, 'graph inputs are writable through animation channels');
registerModifier(geometryNodesDefinition);
const box = MeshBuilder.CreateBox('Cube', { size: 2 }, scene); box.metadata = { wbId: 'cube' };
const objects = [box]; objects.scene = scene;
let history;
const mods = createModifierSystem({ scene, objects, animation }, { commit: () => history?.commit(), notify: m => { throw Error(m); } });
history = createHistory(objects, () => mods.refresh());
const nodes = mods.add(box, 'NODES');
assert.equal(box.getTotalVertices(), 24, 'default Geometry Nodes group passes geometry through');
history.undo(); assert.equal(mods.stack(box).length, 0); history.redo(); assert.equal(mods.stack(box)[0].id, nodes.id);
const logic = createLogic({ scene }, {});
const tick = await logic.add('FlowGraphSceneTickEventBlock', { x: 10, y: 20 });
const log = await logic.add('FlowGraphConsoleLogBlock', { x: 300, y: 20 });
await logic.add('FlowGraphAddBlock', { x: 300, y: 200 });
logic.connect(tick.signalOutputs.find(s => s.name === 'out'), log.signalInputs[0]);
const saved = JSON.parse(JSON.stringify(logic.capture()));
await logic.apply({ blocks: [] });
assert.equal(logic.blocks.length, 0);
await logic.apply(saved);
assert.equal(logic.blocks.length, 3, 'unconnected nodes survive capture/apply');
const restoredTick = logic.blocks.find(b => b.getClassName() === 'FlowGraphSceneTickEventBlock');
assert.equal(restoredTick.signalOutputs.find(s => s.name === 'out')._connectedPoint.length, 1, 'signal links are restored');
assert.deepEqual(logic.position(restoredTick), { x: 10, y: 20 });
logic.dispose();
console.log('Graphs: node material input channels, Geometry Nodes modifier with undo, logic capture/apply passed');
